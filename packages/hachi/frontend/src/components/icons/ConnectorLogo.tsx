// ---------------------------------------------------------------------------
// Registry: connector id → render function
// ---------------------------------------------------------------------------

type LogoRenderer = (size: number) => React.ReactElement

const LOGO_REGISTRY: Record<string, LogoRenderer> = {
  google: (s) => <GoogleLogo size={s} />,
  gmail: (s) => <GmailLogo size={s} />,
  google_calendar: (s) => <GoogleCalendarLogo size={s} />,
  google_drive: (s) => <GoogleDriveLogo size={s} />,
  slack: (s) => <SlackLogo size={s} />,
  notion: (s) => <NotionLogo size={s} />,
  discord: (s) => <DiscordLogo size={s} />,
  whatsapp: (s) => <WhatsAppLogo size={s} />,
  github: (s) => <GitHubLogo size={s} />,
  linear: (s) => <LinearLogo size={s} />,
  telegram: (s) => <TelegramLogo size={s} />,
}

// ---------------------------------------------------------------------------
// Public component
// ---------------------------------------------------------------------------

export function ConnectorLogo({ id, size = 20, style }: ConnectorLogoProps) {
  const renderer = LOGO_REGISTRY[id?.toLowerCase() ?? '']
  if (renderer) {
    return (
      <span
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          flexShrink: 0,
          ...style,
        }}
      >
        {renderer(size)}
      </span>
    )
  }

  // Fallback to the generic Icon component for unknown connector ids.
  return <Icon name="plug" size={size} style={style} />
}
